/** ادغام لایه نمادین با داده پایه نقشه — خروجی، نقشه کامل «خودخوان» است */
export function applyTactics(data: BattleMapData): BattleMapData {
  const t = TACTICS[data.opId]
  if (!t) return data
  return {
    ...data,
    terrain: data.terrain ?? t.terrain,
    nature: data.nature ?? t.nature,
    preFLOT: data.preFLOT ?? t.preFLOT,
    postFLOT: data.postFLOT ?? t.postFLOT,
    liberated: data.liberated ?? t.liberated,
    tricks: data.tricks ?? t.tricks,
    simultaneous: data.simultaneous ?? t.simultaneous,
    phases: data.phases.map(p => {
      const pt = t.phases?.[p.id]
      if (!pt) return p
      return {
        ...p,
        airEvents: [...(pt.airEvents ?? []), ...(p.airEvents ?? [])],
        crossings: [...(pt.crossings ?? []), ...(p.crossings ?? [])],
        defenses: [...(pt.defenses ?? []), ...(p.defenses ?? [])],
        arrows: p.arrows?.map(a => ({ ...a, kind: a.kind ?? pt.arrowKinds?.[a.id] })),
      }
    }),
  }
}
